import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const migrations = new URL("../supabase/migrations/", import.meta.url);
const names = readdirSync(migrations).filter((name) => /^\d+.*\.sql$/.test(name)).sort();
const sections = names.map((name) => {
  // Individual migrations have transaction wrappers; use one outer transaction.
  const sql = readFileSync(new URL(name, migrations), "utf8").replace(/^\s*(begin|commit);\s*$/gim, "").trim();
  return `-- Source: migrations/${name}\n${sql}`;
});
const output = new URL("../supabase/setup.sql", import.meta.url);
writeFileSync(output, `-- GENERATED by npm run db:bundle. Edit migrations, then regenerate.\n-- Fresh Supabase projects only. Run ONCE as administrator in the SQL Editor.\n-- Do not run this alongside the individual migrations or on an existing installation.\n-- Creates application schema, RLS, signup trigger, and flyer Storage bucket.\n\nbegin;\n\n${sections.join("\n\n")}\n\ncommit;\n`);
console.log(`Bundled ${names.length} migrations into ${fileURLToPath(output)}`);
